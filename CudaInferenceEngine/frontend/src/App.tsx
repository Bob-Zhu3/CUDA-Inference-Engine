import { useState } from 'react'
import axios from 'axios'
import { LineChart, Line, XAxis, YAxis, CartesianGrid, Tooltip, Legend, ResponsiveContainer } from 'recharts'
import BenchmarkChart from './BenchmarkChart'

interface LstmResponse {
  output: number[]
}

interface AttentionResponse {
  output: number[]
}

function App() {
  const [lstmOutput, setLstmOutput] = useState<number[]>([])
  const [attnOutput, setAttnOutput] = useState<number[]>([])
  const [loading, setLoading] = useState(false)

  const inputSize = 4
  const seqLen = 5
  const totalElements = inputSize * seqLen

  const runInference = async () => {
    setLoading(true)
    console.log("running inference...")
    
    try {
      const inputData = Array.from({ length: totalElements }, () => Math.random())
      
      console.log("calling lstm endpoint...")
      const lstmRes = await axios.post<LstmResponse>('/api/predict/lstm', { input_data: inputData })
      setLstmOutput(lstmRes.data.output)
      
      console.log("calling attention endpoint...")
      const attnRes = await axios.post<AttentionResponse>('/api/predict/attention', { input_data: inputData })
      setAttnOutput(attnRes.data.output)
      
    } catch (err) {
      console.error("inference failed", err)
    } finally {
      setLoading(false)
    }
  }

  const chartData = lstmOutput.map((val, idx) => ({
    name: `h${idx}`,
    value: val
  }))

  return (
    <div style={{ padding: '20px', fontFamily: 'monospace' }}>
      <h1>CUDA Inference Engine</h1>
      
      <div style={{ maxWidth: '800px', marginBottom: '20px', color: '#555', lineHeight: '1.6' }}>
        <p>
            Note: This demo requires an NVIDIA GPU.
        </p>
        <p>
            This is a demonstration of a high-performance LSTM and attention inference engine running on CUDA. 
            It visualizes the hidden states and attention maps generated by the model in real-time.
            Random numbers are fed into a neural network initialized with random weights. 
            This is a demo to show the speed of the cuda engine rather than the training of a model.
        </p>

        <div style={{ backgroundColor: '#f0f2f5', padding: '15px', borderRadius: '8px', marginTop: '20px', marginBottom: '20px' }}>
          <h3 style={{ marginTop: 0 }}>How it works</h3>
          <p>
            <strong>1. The Data:</strong> We generate a sequence of 5 random input vectors. Each vector has 4 numbers (e.g., <code>[0.1, -0.5, 0.8, 0.2]</code>).
          </p>
          <p>
            <strong>2. LSTM:</strong> For each step, the GPU calculates a new "Hidden State" (short-term memory) based on the input and the previous state.
            <br/>
            <code style={{ display: 'block', margin: '10px 0', padding: '10px', backgroundColor: '#fff', border: '1px solid #ddd' }}>
              new_state = tanh(weight_matrix × input + bias)
            </code>
            The graph on the left plots hidden states over time.
          </p>
          <p>
            <strong>3. Self-Attention:</strong> The grid on the right shows how much each part of the sequence "pays attention" to every other part.
            <br/>
            <code style={{ display: 'block', margin: '10px 0', padding: '10px', backgroundColor: '#fff', border: '1px solid #ddd' }}>
              score = softmax((query × key) / √dimension)
            </code>
            A higher score (brighter blue) means the model thinks two time steps are strongly related.
          </p>
        </div>
      </div>

      <button 
        onClick={runInference} 
        disabled={loading}
        style={{ 
          padding: '10px 20px', 
          fontSize: '16px', 
          cursor: loading ? 'not-allowed' : 'pointer',
          opacity: loading ? 0.7 : 1
        }}
      >
        {loading ? 'running...' : 'run inference'}
      </button>

      <div style={{ display: 'flex', gap: '20px', marginTop: '20px' }}>
        
        <div style={{ flex: 1, border: '1px solid #ccc', padding: '10px' }}>
          <h3>lstm hidden states</h3>
          {lstmOutput.length > 0 ? (
            <ResponsiveContainer width="100%" height={300}>
              <LineChart data={chartData}>
                <CartesianGrid strokeDasharray="3 3" />
                <XAxis dataKey="name" />
                <YAxis />
                <Tooltip />
                <Legend />
                <Line type="monotone" dataKey="value" stroke="#8884d8" />
              </LineChart>
            </ResponsiveContainer>
          ) : (
            <p>no data yet</p>
          )}
        </div>

        <div style={{ flex: 1, border: '1px solid #ccc', padding: '10px' }}>
          <h3>self attention output</h3>
          {attnOutput.length > 0 ? (
            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(4, 1fr)', gap: '5px' }}>
              {attnOutput.map((val, idx) => (
                <div key={idx} style={{ 
                  padding: '5px', 
                  backgroundColor: `rgba(0, 0, 255, ${Math.abs(val)})`,
                  color: Math.abs(val) > 0.5 ? 'white' : 'black',
                  textAlign: 'center'
                }}>
                  {val.toFixed(3)}
                </div>
              ))}
            </div>
          ) : (
            <p>no data yet</p>
          )}
        </div>

      </div>

      <div style={{ marginTop: '40px' }}>
        <BenchmarkChart />
      </div>
    </div>
  )
}

export default App